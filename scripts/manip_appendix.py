#!/usr/bin/env python3
"""Manipulation-check appendix (paper 4, round-5 review m9/m12): per arm, windows, picks, correct picks, and two
explicit nulls — among picks (binomial vs 25%) and over all windows (binomial vs 25%, treating every window as a
guess) — with Wilson 95% CIs. Reads runs/state_pulse/manip_windows.json (MLX parity battery; the paper's Table 3)
and runs/r4/manip_windows.json (torch extension). Writes docs/APPENDIX_MANIP.md."""
from __future__ import annotations

import json
import math
from pathlib import Path

from scipy import stats

ROOT = Path(__file__).resolve().parent.parent
SRC = [("MLX 8-bit parity battery (`runs/state_pulse`; the paper's Table 3)", ROOT / "runs/state_pulse/manip_windows.json"),
       ("PyTorch bf16 extension (`runs/r4`)", ROOT / "runs/r4/manip_windows.json")]


def wilson(k, n, z=1.96):
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    den = 1 + z * z / n
    c = (p + z * z / (2 * n)) / den
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return c - h, c + h


def is_pick(r):
    pk = r.get("picked")
    return pk is not None and pk != "none" and pk != 4


L = ["# Appendix — Manipulation check (auto-generated by scripts/manip_appendix.py)\n",
     "A separate blind judge call (k = 1) names which of the four injected subjects, if any, a window engages, with the options "
     "shuffled per window. `windows` = judged windows; `picks` = windows where the judge named a subject; `correct` = the named "
     "subject is the one injected in that period. Two nulls are reported: among picks (binomial, one-sided, vs 25%) and over all "
     "windows (binomial vs 25%, i.e. treating every window as a guess; conservative). The carrier has no injected subject: its "
     "picks are spurious by definition and its 'none' rate is the base rate. Wilson 95% CIs.\n"]
for title, path in SRC:
    if not path.exists():
        continue
    rows = json.loads(path.read_text())
    L.append(f"## {title}\n")
    L.append("| arm | windows | picks | correct | correct/windows [Wilson] | correct/picks | p (among picks, vs 25%) | p (over windows, vs 25%) | 'none' |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    arms = sorted({r["cond"] for r in rows}, key=lambda a: (a != "habit", a != "inter", a))
    for arm in arms:
        rs = [r for r in rows if r["cond"] == arm]
        n = len(rs); picks = [r for r in rs if is_pick(r)]; npk = len(picks)
        none = n - npk
        if all(r.get("expected") is None for r in rs):
            L.append(f"| {arm} | {n} | {npk} | — (no subject) | — | — | — | — | {none / n:.0%} |")
            continue
        hits = sum(1 for r in picks if r.get("hit"))
        lo, hi = wilson(hits, n)
        p_pick = stats.binomtest(hits, npk, 0.25, alternative="greater").pvalue if npk else float("nan")
        p_win = stats.binomtest(hits, n, 0.25, alternative="greater").pvalue if n else float("nan")
        L.append(f"| {arm} | {n} | {npk} | {hits} | {hits / n:.0%} [{lo:.0%}, {hi:.0%}] | {hits}/{npk} | {p_pick:.2g} | {p_win:.2g} | {none / n:.0%} |")
    L.append("")
out = ROOT / "docs/APPENDIX_MANIP.md"
out.write_text("\n".join(L).rstrip("\n") + "\n")
print("\n".join(L)); print("written", out)
