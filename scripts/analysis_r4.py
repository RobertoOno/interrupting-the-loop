def cellmean(prem, arm, dim, fresh=False, src=res):
    vals = []
    for r in src:
        if r["cell"] != f"{prem}_{arm}" or r.get(dim) is None:
            continue
        if fresh and SC.get(r["cell"], {}).get(str(r["step"]), {}).get("frac", 0) >= 0.5:
            continue
        vals.append(r[dim])
    return float(np.mean(vals)) if vals else None


def paired(a, b, dim, prems=PREMS, fresh=False):
    ds = []
    for p in prems:
        x, y = cellmean(p, a, dim, fresh), cellmean(p, b, dim, fresh)
        if x is not None and y is not None:
            ds.append(x - y)
    return np.asarray(ds, float)


def signflip(d, alt="greater", exact_max=14):
    n = len(d)
    if n == 0:
        return float("nan"), float("nan"), float("nan"), float("nan")
    obs = d.mean()
    stat = (lambda m: m >= obs - 1e-12) if alt == "greater" else (lambda m: abs(m) >= abs(obs) - 1e-12)
    if n <= exact_max:
        cnt = sum(1 for sg in itertools.product((1, -1), repeat=n) if stat((d * np.array(sg)).mean()))
        p = cnt / 2 ** n
    else:  # Monte-Carlo sign-flip, 200k draws, seeded
        sg = np.random.default_rng(1).choice((1, -1), size=(200000, n))
        p = (np.sum([stat(m) for m in (d * sg).mean(1)]) + 1) / (200000 + 1)
    idx = np.random.default_rng(0).integers(0, n, (20000, n))
    lo, hi = np.percentile(d[idx].mean(1), [2.5, 97.5])
    return float(obs), float(lo), float(hi), float(p)


def tost(d, margin):
    """Two one-sided t tests; equivalence when both p < .05 (== IC90 in band)."""
    from scipy import stats
    n = len(d)
    m, sd = d.mean(), d.std(ddof=1)
    se = sd / math.sqrt(n)
    t_lo = (m + margin) / se          # H0: mean <= -margin
    t_hi = (m - margin) / se          # H0: mean >= +margin
    p_lo = 1 - stats.t.cdf(t_lo, n - 1)
    p_hi = stats.t.cdf(t_hi, n - 1)
    tcrit = stats.t.ppf(0.95, n - 1)
    ic90 = (m - tcrit * se, m + tcrit * se)
    return {"mean": m, "sd": sd, "n": n, "ic90": ic90, "p_tost": max(p_lo, p_hi),
            "equiv": max(p_lo, p_hi) < 0.05}


def power_tost(sd, n, margin):
    """Power to declare equivalence when the true difference is 0."""
    from scipy import stats
    se = sd / math.sqrt(n)
    half = stats.t.ppf(0.95, n - 1) * se
    if half >= margin:
        return 0.0
    return float(stats.norm.cdf((margin - half) / se) - stats.norm.cdf(-(margin - half) / se))


def tci_top(d, conf=0.95):
    from scipy import stats
    n = len(d); m = d.mean(); se = d.std(ddof=1) / math.sqrt(max(1, n))
    tc = stats.t.ppf(0.5 + conf / 2, n - 1) if n > 1 else float("nan")
    return m, m - tc * se, m + tc * se


def bh(ps):
    ps = np.asarray(ps, float)
    order = np.argsort(ps)
    q = np.empty(len(ps))
    prev = 1.0
    for rank, i in list(enumerate(order))[::-1]:
        prev = min(prev, ps[i] * len(ps) / (rank + 1))
        q[i] = prev
    return q


def armmean(arm, dim, prems, fresh=False):
    v = [cellmean(p, arm, dim, fresh) for p in prems]
    v = [x for x in v if x is not None]
    return (float(np.mean(v)), len(v)) if v else (float("nan"), 0)


def state_field(prem, arm, key):
    f = R / f"{prem}_{arm}" / "state.json"
    if not f.exists():
        return None
    return json.loads(f.read_text()).get(key)


