def tci(d, conf=0.95):
    from scipy import stats
    n = len(d); m = d.mean(); se = d.std(ddof=1) / math.sqrt(max(1, n))
    tc = stats.t.ppf(0.5 + conf / 2, n - 1) if n > 1 else float("nan")
    return m, m - tc * se, m + tc * se

