#!/usr/bin/env python3
"""Sensitivity of the fresh-only estimates to the self-copy detector.

Requested by a JUDGe 2026 reviewer (QPpH, point 4): do the conclusions hold
for other shingle lengths and overlap thresholds? The primary detector flags
a judged window as copied when at least half of its 12-token shingles occur
earlier in the same stream. Here the shingle length K runs over {8, 12, 16}
and the threshold t over {0.3, 0.5, 0.7}; for each pair we recompute the
copied share, the share whose source lies beyond the judge's 600-token
horizon, and the fresh-only paired contrasts of the interruption over
habituation. Read-only on runs/ (the stream tokens and the existing
judgments); writes docs/APPENDIX_SELFCOPY_SENS.md only.

    python scripts/selfcopy_sensitivity.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from analysis_gen import load_gen, paired  # noqa: E402
from dream_rejudge import stream_ids_and_injections, windows_generated  # noqa: E402

RUNS = ROOT / "runs"
RUN_NAMES = ("dream_scaffold", "dream_b2", "dream_b3", "dream_m", "dream_mplus")
CONDS = {"bare_habit": "habituation", "bare_reseed": "interruption 150",
         "clock300": "interruption 300", "reset_reseed300": "reset + new subject 300"}
CONTRASTS = (("bare_reseed", "bare_habit", "interruption 150 vs habituation"),
             ("clock300", "bare_habit", "interruption 300 vs habituation"))
KS, TS, HORIZON, WIN = (8, 12, 16), (0.3, 0.5, 0.7), 600, 96


def cell_fracs(cell_dir: Path, tok) -> dict:
    """{step: {K: (frac seen anywhere earlier, frac seen within the horizon)}}"""
    ids, _pts, _seed = stream_ids_and_injections(cell_dir, tok)
    out = {}
    for w in windows_generated(cell_dir, tok):
        ws = w["step"]
        win, before = ids[ws: ws + WIN], ids[:ws]
        recent = before[max(0, ws - HORIZON):]
        per_k = {}
        for k in KS:
            seen = {tuple(before[i:i + k]) for i in range(len(before) - k + 1)}
            near = {tuple(recent[i:i + k]) for i in range(len(recent) - k + 1)}
            sh = [tuple(win[i:i + k]) for i in range(len(win) - k + 1)]
            n = max(1, len(sh))
            per_k[k] = (sum(g in seen for g in sh) / n, sum(g in near for g in sh) / n)
        out[str(ws)] = per_k
    return out


def main() -> None:
    from mlx_lm.utils import load_tokenizer  # tokenizer only, never the weights
    tok = load_tokenizer(Path("~/models/mlx/Qwen3-30B-A3B-Base-8bit").expanduser())
    rows = [r for name in RUN_NAMES for r in load_gen(name)]
    rows = [r for r in rows if r["cond"] in CONDS and r.get("since") in (32, None)]
    cells = sorted({(r["run"], r["cell"]) for r in rows})
    fr = {}
    for run, cell in cells:
        fr[(run, cell)] = cell_fracs(RUNS / run / cell, tok)
    print(f"{len(rows)} judged windows, {len(cells)} cells", flush=True)

    md = ["# Appendix: sensitivity of the fresh-only estimates to the self-copy detector "
          "(auto-generated by scripts/selfcopy_sensitivity.py)\n",
          "A window is *copied* when a share of at least t of its K-token shingles occurs earlier "
          "in the same stream; *beyond the horizon* when it is copied and its source is not within "
          "the 600 tokens shown to the judge (share seen within the horizon below t). Primary "
          "detector: K = 12, t = 0.5. Windows: the first generated-only window after each "
          "injection (grid windows in the uninterrupted arm), Qwen3-30B-A3B-Base, ten premises. "
          "Fresh-only contrasts are paired over premises (exact sign-flip permutation, bootstrap "
          "95% CI over premises).\n",
          "## Copied share and share beyond the horizon\n",
          "| K | t | " + " | ".join(f"{v}: copied / beyond" for v in CONDS.values()) + " |",
          "|---|---|" + "---|" * len(CONDS)]
    contrast_rows = []
    for k in KS:
        for t in TS:
            def flag(r):
                return fr[(r["run"], r["cell"])].get(str(r["step"]), {}).get(k)
            cells_md, fresh = [], {}
            for c in CONDS:
                rs = [r for r in rows if r["cond"] == c and flag(r) is not None]
                cop = [r for r in rs if flag(r)[0] >= t]
                beyond = [r for r in cop if flag(r)[1] < t]
                cells_md.append(f"{100 * len(cop) / max(1, len(rs)):.0f}% / {100 * len(beyond) / max(1, len(rs)):.0f}%")
                by = {}
                for r in rs:
                    if flag(r)[0] < t:
                        by.setdefault(r["seed"], {d: [] for d in ("surprise", "connection")})
                        for d in ("surprise", "connection"):
                            by[r["seed"]][d].append(r[d])
                fresh[c] = {d: {s: float(np.mean(v[d])) for s, v in by.items()} for d in ("surprise", "connection")}
            mark = " (primary)" if (k, t) == (12, 0.5) else ""
            md.append(f"| {k} | {t}{mark} | " + " | ".join(cells_md) + " |")
            for a, b, lab in CONTRASTS:
                for d in ("surprise", "connection"):
                    pr = paired(fresh[a][d], fresh[b][d])
                    if pr:
                        contrast_rows.append(f"| {k} | {t}{mark} | {lab} | {d} | {pr['mean']:+.2f} "
                                             f"[{pr['lo']:+.2f}, {pr['hi']:+.2f}] | {pr['p_perm']:.3f} | {pr['n']} |")
    md += ["\n## Fresh-only contrasts under each detector setting\n",
           "| K | t | contrast | dim | Δ [95% CI] | p (perm) | n premises |",
           "|---|---|---|---|---|---|---|"] + contrast_rows
    out = ROOT / "docs" / "APPENDIX_SELFCOPY_SENS.md"
    out.write_text("\n".join(md) + "\n")
    print("\n".join(md))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
